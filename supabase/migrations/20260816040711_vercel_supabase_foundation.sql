-- DCAL Vercel/Supabase foundation.
-- Clinical pages remain private. Human users authenticate through Supabase Auth;
-- authorization comes only from public.profiles.role/active, never user metadata.

create schema if not exists dcal_private;
revoke all on schema dcal_private from public, anon;
grant usage on schema dcal_private to authenticated;

do $$
begin
  create type public.dcal_member_role as enum ('annotator', 'reviewer', 'admin');
exception
  when duplicate_object then null;
end
$$;

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Pending user'
    check (char_length(btrim(display_name)) between 1 and 100),
  role public.dcal_member_role not null default 'annotator',
  active boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.tasks (
  id bigint generated by default as identity primary key,
  ingestion_key text not null unique
    check (ingestion_key ~ '^task_[0-9a-f]{32}$'),
  source_origin text not null
    check (source_origin in ('manual_upload', 'google_drive')),
  dataset_eligible boolean not null default false,
  source_object_id text not null,
  source_sha256 text not null unique
    check (source_sha256 ~ '^[0-9a-f]{64}$'),
  raw_source_sha256 text
    check (raw_source_sha256 is null or raw_source_sha256 ~ '^[0-9a-f]{64}$'),
  patient_group_id text,
  encounter_group_id text,
  writer_group_ids jsonb not null default '[]'::jsonb
    check (jsonb_typeof(writer_group_ids) = 'array'),
  source_page_index integer not null default 1
    check (source_page_index > 0),
  ingestion_schema_version text,
  render_profile text not null,
  storage_bucket text not null default 'dcal-pages'
    check (storage_bucket = 'dcal-pages'),
  storage_path text not null unique
    check (storage_path !~ '(^|/)\.\.(/|$)'),
  image_width integer not null check (image_width > 0),
  image_height integer not null check (image_height > 0),
  status text not null default 'unassigned'
    check (status in ('unassigned', 'in_progress', 'completed', 'needs_review')),
  assigned_to uuid references public.profiles(id) on delete set null,
  assigned_to_name text,
  annotation jsonb not null default jsonb_build_object(
    'schema_version', 'dcal.annotation.v2',
    'document_type', null,
    'document_variant', null,
    'content_profile', null,
    'image_quality', jsonb_build_array(),
    'notes', '',
    'regions', jsonb_build_array()
  ),
  version integer not null default 1 check (version > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  completed_at timestamptz,
  constraint tasks_annotation_shape check (
    jsonb_typeof(annotation) = 'object'
    and annotation ->> 'schema_version' = 'dcal.annotation.v2'
    and jsonb_typeof(annotation -> 'regions') = 'array'
    and jsonb_typeof(annotation -> 'image_quality') = 'array'
  ),
  constraint tasks_provenance_bundle check (
    (
      source_origin = 'manual_upload'
      and dataset_eligible = false
      and patient_group_id is null
      and encounter_group_id is null
      and ingestion_schema_version is null
    )
    or
    (
      source_origin = 'google_drive'
      and dataset_eligible = true
      and patient_group_id is not null
      and encounter_group_id is not null
      and raw_source_sha256 is not null
      and ingestion_schema_version = 'dcal.ingestion.v1'
    )
  )
);

create table public.revisions (
  id bigint generated by default as identity primary key,
  task_id bigint not null references public.tasks(id) on delete cascade,
  version integer not null check (version > 1),
  actor_user_id uuid references public.profiles(id) on delete set null,
  actor_name text not null check (char_length(btrim(actor_name)) between 1 and 100),
  action text not null check (action in ('save', 'complete')),
  annotation jsonb not null,
  created_at timestamptz not null default now(),
  unique (task_id, version)
);

create index tasks_status_updated_idx on public.tasks(status, updated_at desc);
create index tasks_document_type_idx on public.tasks((annotation ->> 'document_type'));
create index tasks_dataset_eligible_idx on public.tasks(dataset_eligible)
  where dataset_eligible = true;
create index revisions_task_created_idx on public.revisions(task_id, created_at desc);
create index tasks_assigned_to_idx on public.tasks(assigned_to)
  where assigned_to is not null;
create index revisions_actor_user_idx on public.revisions(actor_user_id)
  where actor_user_id is not null;

alter table public.profiles enable row level security;
alter table public.tasks enable row level security;
alter table public.revisions enable row level security;

create or replace function dcal_private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles(id, display_name)
  values (
    new.id,
    coalesce(nullif(btrim(new.raw_user_meta_data ->> 'display_name'), ''), 'Pending user')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists dcal_auth_user_created on auth.users;
create trigger dcal_auth_user_created
  after insert on auth.users
  for each row execute function dcal_private.handle_new_user();

create or replace function dcal_private.is_active_member(member_id uuid default auth.uid())
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles
    where id = member_id and active = true
  );
$$;

revoke all on function dcal_private.is_active_member(uuid) from public, anon, authenticated;
grant execute on function dcal_private.is_active_member(uuid) to service_role;

